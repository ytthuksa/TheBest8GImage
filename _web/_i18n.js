let LANG = "zh";
try { LANG = localStorage.getItem("qwen21_lang") || "zh"; } catch (e) { LANG = "zh"; }
if (LANG !== "zh" && LANG !== "en") LANG = "zh";

/* 取词 + 占位符替换：t("pill.queue", {run:1, pend:2}) */
function t(key, vars) {
  const tb = I18N[LANG] || I18N.zh;
  let s = tb[key];
  if (s == null) s = I18N.zh[key];
  if (s == null) return key;
  if (vars) {
    for (const k in vars) s = s.split("{" + k + "}").join(vars[k]);
  }
  return s;
}

/* 把静态 HTML 里所有 data-i18n 元素刷一遍 */
function applyI18n() {
  document.querySelectorAll("[data-i18n]").forEach(n => {
    const k = n.getAttribute("data-i18n");
    const v = t(k);
    if (v != null) n.innerHTML = v;
  });
  document.querySelectorAll("[data-i18n-ph]").forEach(n => {
    n.setAttribute("placeholder", t(n.getAttribute("data-i18n-ph")));
  });
  document.querySelectorAll("[data-i18n-title]").forEach(n => {
    n.setAttribute("title", t(n.getAttribute("data-i18n-title")));
  });
  document.querySelectorAll("[data-i18n-html]").forEach(n => {
    n.innerHTML = t(n.getAttribute("data-i18n-html"));
  });
  document.documentElement.lang = LANG === "zh" ? "zh-CN" : "en";
  document.title = t("app.title");
  const lb = document.getElementById("lang-btn");
  if (lb) { lb.textContent = t("lang.switch"); lb.title = t("lang.title"); }
}

function setLang(l) {
  LANG = (l === "en") ? "en" : "zh";
  try { localStorage.setItem("qwen21_lang", LANG); } catch (e) {}
  applyI18n();
  // 通知各处重绘动态文案
  if (typeof refreshDynamicText === "function") refreshDynamicText();
}
